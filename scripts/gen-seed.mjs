#!/usr/bin/env node
/**
 * Generate worker/seed.sql from src/data/projects.ts, so the D1 `projects`
 * table always matches the local fallback list.
 *
 *   node scripts/gen-seed.mjs
 *   cd worker && npx wrangler d1 execute aroi-me --remote --file=seed.sql
 *
 * Node 22.6+ can import the .ts file directly (type stripping).
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { projects } from '../src/data/projects.ts'

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)
const b = (v) => (v ? 1 : 0)

const rows = projects.map(
  (p) =>
    `(${[
      q(p.slug),
      q(p.title),
      q(p.tagline),
      q(p.summary),
      q(JSON.stringify(p.highlights)),
      q(JSON.stringify(p.tech)),
      q(p.repoUrl),
      q(p.demoUrl),
      q(p.image),
      q(p.video),
      b(p.isPrivate),
      b(p.embeddable),
      b(p.featured),
      1,
      p.order,
      q(p.year),
    ].join(', ')})`,
)

const sql = `-- Generated by scripts/gen-seed.mjs from src/data/projects.ts. Do not edit by hand.
INSERT OR REPLACE INTO projects
  (slug, title, tagline, summary, highlights, tech_stack, repo_url, demo_url, image_url, video_url, is_private, embeddable, featured, published, display_order, year)
VALUES
${rows.join(',\n')};
`

const out = fileURLToPath(new URL('../worker/seed.sql', import.meta.url))
writeFileSync(out, sql)
console.log(`Wrote ${projects.length} projects to worker/seed.sql`)
